CREATE TABLE IF NOT EXISTS `transports` (
  `transport_id` INT NOT NULL AUTO_INCREMENT,
  `asset_code` VARCHAR(255) NOT NULL,
  `asset_name` VARCHAR(255) NOT NULL,
  `vehicle_number` VARCHAR(100) NULL,
  `engine_number` VARCHAR(100) NULL,
  `chassis_number` VARCHAR(100) NULL,
  `acquisition_type` VARCHAR(50) NOT NULL,
  `dependency_type` VARCHAR(50) NOT NULL,
  `working_status` VARCHAR(50) NOT NULL,
  `asset_description` TEXT NULL,
  `customer_asset_no` VARCHAR(100) NULL,
  `sub_category` VARCHAR(100) NULL,
  `hsn_code` VARCHAR(50) NULL,
  `barcode_option` VARCHAR(50) NULL,
  `barcode_no` VARCHAR(100) NULL,
  `purchased_price` DECIMAL(15,2) NULL,
  `purchased_date` DATE NULL,
  `placed_in_service` DATE NULL,
  `capitalization_date` DATE NULL,
  `bill_no` VARCHAR(100) NULL,
  `bill_date` DATE NULL,
  `received_date` DATE NULL,
  `serial_number` VARCHAR(100) NULL,
  `model_number` VARCHAR(100) NULL,
  `seller` VARCHAR(255) NULL,
  `branch_id` INT NULL,
  `is_depreciation_applicable` VARCHAR(3) NOT NULL DEFAULT 'No',
  `salvage_value` DECIMAL(15,2) NULL,
  `exp_end_date` DATE NULL,
  `asset_life_span` INT NULL,
  `image_url` VARCHAR(500) NULL,
  `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`transport_id`),
  UNIQUE KEY `unique_asset_code` (`asset_code`),
  KEY `idx_transports_branch_id` (`branch_id`),
  CONSTRAINT `fk_transports_branch`
    FOREIGN KEY (`branch_id`) REFERENCES `branches`(`branch_id`)
    ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;