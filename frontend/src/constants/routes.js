const createRoute = (routeConfig) => ({
  routeName: routeConfig.title,
  routePath: routeConfig.path,
  permissionKey: routeConfig.permissionKey,
});

/** Top-level sidebar modules (rail) — aligns with MENU_MODULES in Menu.js */
const TOP_LEVEL_MODULES = {
  all: {
    name: "All",
    icon: "fa-layer-group",
    color: "brand",
  },
  wms: {
    name: "WMS",
    icon: "fa-warehouse",
    color: "pink",
  },
};

const createModuleRoutes = (topLevelKey, sectionModule, routeConfigs) => {
  const topLevel = TOP_LEVEL_MODULES[topLevelKey];
  return {
    topLevelModuleId: topLevelKey,
    topLevelModuleName: topLevel.name,
    topLevelModuleIcon: topLevel.icon,
    topLevelModuleColorPalette: topLevel.color,
    moduleColorPalette: sectionModule.color,
    moduleIcon: sectionModule.icon,
    moduleName: sectionModule.name,
    routes: routeConfigs.map(createRoute),
  };
};

